"""
آموزش پایتون - متغیرها (Variables)

متغیر یعنی محلی در حافظه که یک مقدار را داخل آن ذخیره می‌کنیم
تا هر زمان که لازم بود دوباره از آن استفاده کنیم.
"""

# ==========================================
# عدد صحیح (Integer)
# ==========================================
# عددی بدون اعشار

student_count = 87
imdb_score = 12

print(student_count)
print(imdb_score)


# ==========================================
# عدد اعشاری (Float)
# ==========================================

rating = 4.99
price = 19.90

print(rating)
print(price)


# ==========================================
# مقدار منطقی (Boolean)
# ==========================================
# فقط دو مقدار دارد:
# True  = درست
# False = نادرست

is_hungry = False
is_logged_in = True

print(is_hungry)
print(is_logged_in)


# ==========================================
# رشته (String)
# ==========================================
# متن همیشه داخل "" یا '' نوشته می‌شود.

favorite_food = "Pizza 🍕"
student_name = "Sara"

print(favorite_food)
print(student_name)


# ==========================================
# قوانین نام‌گذاری متغیرها
# ==========================================

# 1) از اسم‌های معنی‌دار استفاده کن.
c1 = "Python"              # 👎
course_name = "Python"     # 👍


# 2) نام متغیرها را با حروف کوچک بنویس.
Name = "Sara"              # 👎
name = "Sara"              # 👍


# 3) بین کلمه‌ها از _ استفاده کن.
studentcount = 87          # 👎
student_count = 87         # 👍


# 4) قبل و بعد از = یک فاصله قرار بده.
course_name = "Python"       # 👎
course_name = "Python"     # 👍


