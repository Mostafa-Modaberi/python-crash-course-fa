# ==========================================
# تمرین 2 (چالش)
# ==========================================
#
# یک فروشگاه کتاب، سه کتاب با قیمت‌های مختلف می‌فروشد.
#
# از کاربر قیمت هر سه کتاب را دریافت کن.
#
# سپس:
#
# 1- مجموع قیمت‌ها را محاسبه کن.
# 2- میانگین قیمت کتاب‌ها را محاسبه کن.
# 3- مجموع را تا 2 رقم اعشار گرد کن.
# 4- بررسی کن که آیا میانگین قیمت بیشتر از 20 است یا نه.
# 5- نتیجه را با یک جمله کامل چاپ کن.
#
#
# نمونه ورودی
#
# Book 1 price: 15.5
# Book 2 price: 22
# Book 3 price: 18.75
#
#
# نمونه خروجی
#
# 56.25
# 18.75
# False
# Average price: 18.75
