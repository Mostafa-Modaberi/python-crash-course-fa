"""
آموزش پایتون - دریافت ورودی (Input)

با استفاده از تابع 
input() 
می‌توان از کاربر اطلاعات دریافت کرد
نکته مهم این است که 
input()
همیشه مقدار را به صورت رشته 
(String)
برمی‌گرداند
"""

# ==========================================
# دریافت ورودی از کاربر
# ==========================================

name = input("What is your name? ")

print(f"Hello {name}!")


# ==========================================
# input همیشه رشته برمی‌گرداند
# ==========================================

age = input("How old are you? ")

print(age)
print(type(age))


# ==========================================
# تبدیل نوع داده (Casting)
# ==========================================

# تبدیل رشته به عدد صحیح

age = int(age)

print(age)
print(type(age))

print(f"Next year you will be {age + 1} years old.")


# ==========================================
# توابع تبدیل نوع داده
# ==========================================

number = "25"

print(int(number))
print(float(number))
print(bool(number))
print(str(number))


# ==========================================
# مقادیر False (انواع نه گفتن در پایتون)
# ==========================================

# مقادیر زیر در پایتون False محسوب می‌شوند.

print(bool(""))
print(bool(0))
print(bool(None))


# تقریباً همه مقادیر دیگر True هستند.

print(bool("Python"))
print(bool(15))
print(bool(-1))


# ==========================================
# مشکل جمع رشته‌ها
# ==========================================

first_number = input("Enter the first number: ")
second_number = input("Enter the second number: ")

print(first_number + second_number)

# چرا؟
# چون هر دو مقدار هنوز از نوع String هستند.


# ==========================================
# تبدیل رشته به عدد
# ==========================================

first_number = int(first_number)
second_number = int(second_number)

print(first_number + second_number)

print(
    f"{first_number} + {second_number} = {first_number + second_number}"
)


# ==========================================
# کار با اعداد اعشاری
# ==========================================

price = float(input("Enter the product price: "))
tax = float(input("Enter the tax amount: "))

total_price = price + tax

print(total_price)

print(f"Total Price: {round(total_price, 2)}")


# ==========================================
# بررسی نوع داده
# ==========================================

print(type(first_number))
print(type(price))
print(type(name))


# ==========================================
# مثال واقعی
# ==========================================

movie_name = input("Movie name: ")
movie_rating = float(input("Movie rating: "))

print(f"{movie_name} has a rating of {movie_rating}.")


