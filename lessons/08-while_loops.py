"""
آموزش پایتون - حلقه while

در این درس با حلقه while، شرط حلقه، تغییر مقدار متغیر،
حلقه‌های بی‌نهایت، break، continue و while...else آشنا می‌شویم.
"""

# ==========================================
# حلقه while چیست؟
# ==========================================

# از حلقه while زمانی استفاده می‌کنیم که بخواهیم
# یک بخش از برنامه تا زمانی که یک شرط برقرار است،
# چندین بار اجرا شود.
#
# ساختار کلی:
#
# while condition:
#     code


# ==========================================
# یک مثال ساده
# ==========================================

number = 1

while number <= 5:
    print(number)
    number += 1

# در این مثال:
# 1. مقدار number برابر 1 است.
# 2. شرط number <= 5 بررسی می‌شود.
# 3. اگر شرط True باشد، کد داخل حلقه اجرا می‌شود.
# 4. مقدار number یک واحد افزایش پیدا می‌کند.
# 5. این کار تا زمانی ادامه پیدا می‌کند که شرط False شود.


# ==========================================
# اهمیت تغییر مقدار متغیر
# ==========================================

# اگر متغیر مورد استفاده در شرط را تغییر ندهیم،
# ممکن است حلقه هیچ‌وقت تمام نشود.

number = 5

while number > 0:
    print(number)
    number -= 1

# در هر تکرار یک واحد از number کم می‌شود.
# وقتی number به صفر برسد، شرط False می‌شود
# و حلقه پایان پیدا می‌کند.


# ==========================================
# مثال: تقسیم عدد بر 2
# ==========================================

number = 100

while number > 0:
    print(number)
    number //= 2

# عمل // تقسیم صحیح انجام می‌دهد.
#
# مقدارهای number تقریباً به این شکل خواهند بود:
# 100
# 50
# 25
# 12
# 6
# 3
# 1
#
# وقتی number به صفر برسد، حلقه تمام می‌شود.


# ==========================================
# while در برابر for
# ==========================================

# زمانی که تعداد تکرارها را از قبل می‌دانیم،
# معمولاً for انتخاب مناسبی است.

for number in range(1, 6):
    print(number)


# زمانی که پایان حلقه به یک شرط وابسته است،
# while معمولاً انتخاب مناسب‌تری است.

number = 1

while number <= 5:
    print(number)
    number += 1


# ==========================================
# دریافت ورودی تا زمانی که کاربر exit بزند
# ==========================================

# یکی از کاربردهای رایج while این است که
# تا زمانی که کاربر یک دستور خاص وارد نکرده،
# برنامه ادامه پیدا کند.

command = ""

while command.lower() != "exit":
    command = input("> ")
    print("ECHO", command)

# lower() حروف انگلیسی را به حروف کوچک تبدیل می‌کند.
#
# بنابراین همه این ورودی‌ها باعث پایان حلقه می‌شوند:
#
# exit
# EXIT
# Exit
# ExIt
#
# چون قبل از مقایسه، متن با lower() به حروف کوچک تبدیل می‌شود.


# ==========================================
# استفاده از strip برای ورودی
# ==========================================

# گاهی کاربر قبل یا بعد از ورودی فاصله وارد می‌کند.
# strip() فاصله‌های اضافی ابتدا و انتهای متن را حذف می‌کند.

command = ""

while command.lower().strip() != "exit":
    command = input("> ")
    print("ECHO", command)

# حالا این ورودی‌ها نیز به عنوان exit شناخته می‌شوند:
#
# exit
# EXIT
# Exit
#   exit
# exit


# ==========================================
# حلقه بی‌نهایت
# ==========================================

# اگر شرط while همیشه True باشد،
# حلقه به صورت طبیعی هیچ‌وقت تمام نمی‌شود.

# while True:
#     print("Hello")

# این نوع حلقه را Infinite Loop می‌نامیم.
#
# از حلقه بی‌نهایت زمانی استفاده می‌کنیم که بخواهیم
# خودمان با استفاده از break مشخص کنیم چه زمانی حلقه تمام شود.


# ==========================================
# حلقه بی‌نهایت با break
# ==========================================

while True:
    command = input("> ")

    if command.lower().strip() == "exit":
        break

    print("ECHO", command)

# break باعث می‌شود حلقه بلافاصله متوقف شود.
#
# در این مثال:
# - برنامه دائماً منتظر دریافت دستور است.
# - اگر دستور exit باشد، break اجرا می‌شود.
# - در غیر این صورت، دستور چاپ می‌شود.


# ==========================================
# دستور continue
# ==========================================

# continue باعث می‌شود ادامه کدهای داخل حلقه
# در همان تکرار اجرا نشوند و برنامه به تکرار بعدی برود.

number = 0

while number < 10:
    number += 1

    if number % 2 == 0:
        continue

    print(number)

# در این مثال:
# اگر عدد زوج باشد، continue اجرا می‌شود
# و print برای آن عدد اجرا نمی‌شود.
#
# بنابراین فقط عددهای فرد چاپ می‌شوند.


# ==========================================
# مثال: چاپ اعداد فرد
# ==========================================

number = 1

while number <= 10:
    print(number)
    number += 2


# ==========================================
# شمارش تعداد تکرارها
# ==========================================

# می‌توانیم با استفاده از یک متغیر،
# تعداد دفعات اجرای حلقه را بشماریم.

number = 1
count = 0

while number <= 10:
    print(number)

    count += 1
    number += 1

print("Count:", count)


# ==========================================
# مثال واقعی: دریافت عدد معتبر
# ==========================================

# فرض کنید می‌خواهیم سن کاربر را دریافت کنیم.
# اگر عدد واردشده منفی باشد، دوباره از کاربر ورودی می‌گیریم.

age = int(input("Enter your age: "))

while age < 0:
    print("Age cannot be negative.")
    age = int(input("Enter your age: "))

print(f"Your age is {age}")


# ==========================================
# while ... else
# ==========================================

# حلقه while نیز مانند for می‌تواند else داشته باشد.
#
# بخش else زمانی اجرا می‌شود که حلقه به صورت عادی
# به پایان برسد و با break متوقف نشده باشد.

number = 1

while number <= 3:
    print(number)
    number += 1
else:
    print("Loop finished")


# ==========================================
# while ... else با break
# ==========================================

number = 1

while number <= 5:
    print(number)

    if number == 3:
        break

    number += 1
else:
    print("Loop finished")

# چون حلقه با break متوقف شده است،
# بخش else اجرا نمی‌شود.


# ==========================================
# مثال واقعی: رمز عبور
# ==========================================

password = "1234"
attempts = 0

while attempts < 3:
    user_password = input("Enter password: ")
    attempts += 1

    if user_password == password:
        print("Successful")
        break

    print("Wrong password")

else:
    print("Account locked")


# ==========================================
# ترکیب while و شرط‌ها
# ==========================================

# در برنامه‌های واقعی معمولاً while را
# همراه با if و else استفاده می‌کنیم.

number = 1

while number <= 10:
    if number % 2 == 0:
        print(f"{number} is even")
    else:
        print(f"{number} is odd")

    number += 1


# ==========================================
# مثال کاربردی: جمع اعداد
# ==========================================

# در این مثال تا زمانی که کاربر عدد صفر را وارد نکرده،
# اعداد دریافت می‌شوند و با هم جمع می‌شوند.

total = 0

while True:
    number = int(input("Enter a number (0 to finish): "))

    if number == 0:
        break

    total += number

print(f"Total: {total}")


