"""
آموزش پایتون - حلقه for

در این درس با حلقه for، تابع range، دستورات break و else،
حلقه‌های تو در تو و مفهوم iterable آشنا می‌شویم.
"""

# ==========================================
# حلقه for
# ==========================================

# وقتی بخواهیم یک کار را چند بار تکرار کنیم،
# می‌توانیم از حلقه for استفاده کنیم.

print("Attempt...")
print("Attempt...")
print("Attempt...")

# به جای نوشتن چندباره کد، می‌توانیم از for استفاده کنیم.
for number in range(3):
    print("Attempt")

# متغیر number در هر تکرار، شماره تکرار را نگه می‌دارد.
# چون range(3) از صفر شروع می‌شود، مقدارهای number برابر 0، 1 و 2 هستند.

for number in range(3):
    print("Attempt", number + 1)


# ==========================================
# تابع range
# ==========================================

# range() برای ساختن یک دنباله از اعداد استفاده می‌شود.
#
# اگر فقط یک عدد به range بدهیم،
# شمارش از صفر شروع می‌شود و تا یک عدد قبل از آن ادامه پیدا می‌کند.

for number in range(3):
    print(number)

# خروجی:
# 0
# 1
# 2


# ==========================================
# range با start و stop
# ==========================================

# می‌توانیم مشخص کنیم شمارش از چه عددی شروع شود.
#
# range(start, stop)
#
# عدد start در دنباله قرار می‌گیرد،
# اما stop در دنباله قرار نمی‌گیرد.

for number in range(1, 4):
    print(number)

# خروجی:
# 1
# 2
# 3


# مثال کاربردی
for number in range(1, 4):
    print("Attempt", number)


# ==========================================
# range با start، stop و step
# ==========================================

# آرگومان سوم range مشخص می‌کند
# که در هر مرحله چند واحد جلو برویم.
#
# range(start, stop, step)

for number in range(1, 10, 2):
    print(number)

# خروجی:
# 1
# 3
# 5
# 7
# 9


# مثال:
# در اینجا عددها دو تا دو تا افزایش پیدا می‌کنند.
for number in range(1, 11, 2):
    print("Number:", number)


# ==========================================
# استفاده از for برای ایجاد شمارنده
# ==========================================

# می‌توانیم هنگام هر تکرار، اطلاعات بیشتری نمایش دهیم.
for number in range(1, 4):
    print("Attempt", number, "." * number)

# در این مثال:
# تکرار اول: .
# تکرار دوم: ..
# تکرار سوم: ...


# ==========================================
# دستور break
# ==========================================

# گاهی لازم است قبل از تمام شدن حلقه،
# اجرای آن را متوقف کنیم.
#
# برای این کار از break استفاده می‌کنیم.

successful = True

for number in range(3):
    print("Attempt")

    if successful:
        print("Successful")
        break

# وقتی break اجرا شود، حلقه بلافاصله متوقف می‌شود.


# ==========================================
# for ... else
# ==========================================

# حلقه for می‌تواند یک بخش else هم داشته باشد.
#
# else زمانی اجرا می‌شود که حلقه به صورت عادی
# تمام شود و با break متوقف نشده باشد.

successful = False

for number in range(3):
    print("Attempt")

    if successful:
        print("Successful")
        break
else:
    print("Attempted 3 times and failed")

# در این مثال successful برابر False است،
# بنابراین break اجرا نمی‌شود و حلقه به پایان می‌رسد.
# در نتیجه بخش else اجرا می‌شود.


# ==========================================
# مثال واقعی: بررسی رمز عبور
# ==========================================

# فرض کنید کاربر فقط سه بار فرصت دارد رمز عبور را وارد کند.

password = "1234"

for number in range(3):
    user_password = input(
        f"-> {number + 1}: Enter password: "
    )

    if user_password == password:
        print("\n>> Successful\n")
        break

    remaining_attempts = 3 - (number + 1)
    print(f">> Wrong Password, {remaining_attempts} Try left")

else:
    print("\n>> Attempted 3 times and failed\n")

# اگر رمز درست باشد:
# break اجرا می‌شود و else اجرا نخواهد شد.
#
# اگر هر سه تلاش اشتباه باشند:
# حلقه بدون break تمام می‌شود و else اجرا خواهد شد.


# ==========================================
# حلقه‌های تو در تو
# ==========================================

# یک حلقه for می‌تواند داخل حلقه for دیگری قرار بگیرد.
# به این نوع ساختار Nested Loop یا حلقه تو در تو می‌گوییم.

for x in range(5):
    for y in range(3):
        print(f"({x}, {y})")

# برای هر مقدار x، حلقه داخلی به صورت کامل اجرا می‌شود.
#
# برای مثال:
# x = 0 -> y = 0, 1, 2
# x = 1 -> y = 0, 1, 2
# ...


# ==========================================
# مثال کاربردی از حلقه تو در تو
# ==========================================

# فرض کنید می‌خواهیم یک جدول ساده از شماره صندلی‌ها بسازیم.

for row in range(1, 4):
    for seat in range(1, 5):
        print(f"Row {row}, Seat {seat}")


# ==========================================
# Iterable چیست؟
# ==========================================

# حلقه for می‌تواند روی مجموعه‌ای از داده‌ها حرکت کند.
# به اشیایی که می‌توان روی عناصر آن‌ها یکی‌یکی حرکت کرد،
# Iterable گفته می‌شود.

print(type(5))
print(type(range(5)))

# عدد 5 یک iterable نیست،
# اما range(5) یک iterable است.


# ==========================================
# پیمایش رشته با for
# ==========================================

# رشته‌ها نیز iterable هستند.
# بنابراین می‌توانیم حروف یک رشته را یکی‌یکی دریافت کنیم.

for character in "Python":
    print(character)


# ==========================================
# پیمایش لیست با for
# ==========================================

# لیست‌ها نیز iterable هستند.
# بنابراین می‌توانیم عناصر لیست را یکی‌یکی دریافت کنیم.

fruits = ["apple", "orange", "banana"]

for fruit in fruits:
    print(fruit)


# ==========================================
# مثال واقعی: نمایش نام دانش‌آموزان
# ==========================================

students = ["Sara", "Ali", "Reza", "Mina"]

for student in students:
    print(f"Student: {student}")


# ==========================================
# مثال واقعی: محاسبه مجموع خریدها
# ==========================================

prices = [120, 250, 80, 150]
total_price = 0

for price in prices:
    total_price += price

print(f"Total: {total_price}")


