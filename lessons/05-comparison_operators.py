#
# سپس بررسی کنید که آیا سن دانش‌آموز اول از دانش‌آموز دوم بیشتر است یا خیر.
#
# در پایان موارد زیر را نمایش دهید:
# - نام دانش‌آموز اول
# - نام دانش‌آموز دوم
# - نتیجه مقایسه سن آن‌ها (True یا False)
#
# نمونه ورودی
#
# First student name: Ali
# First student age: 18
# Second student name: Sara
# Second student age: 16
#
# نمونه خروجی
#
# Ali
# Sara
# True

# ==========================================
# تمرین 2 (چالشی)
# ==========================================

# یک برنامه بنویسید که اطلاعات دو محصول را از کاربر دریافت کند.
#
# برای هر محصول موارد زیر را بگیرید:
# - نام محصول
# - قیمت
#
# سپس برنامه باید موارد زیر را نمایش دهد:
#
# - آیا قیمت دو محصول برابر است؟
# - آیا محصول اول گران‌تر از محصول دوم است؟
# - آیا محصول دوم ارزان‌تر یا مساوی محصول اول است؟
# - آیا نام دو محصول دقیقا یکسان است؟ (حساس به حروف بزرگ و کوچک)
# - در نهایت فاکتور جمع دو محصول را نمایش دهد
#
# در انتها با استفاده از f-string یک جمله مانند نمونه زیر چاپ کنید:
#
# Laptop costs more than Mouse: True
#
# نمونه ورودی
#
# First product: Laptop
# First price: 42000
# Second product: Mouse
# Second price: 1800
#
# نمونه خروجی
#
# Equal prices: False
# First product is more expensive: True
# Second product is cheaper or equal: True
# Same name: False
# Laptop costs more than Mouse: True
#
# Laptop : 42000
# Mouse : 1800
# ------------------
# full price : 43800
