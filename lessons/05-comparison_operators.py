"""
آموزش پایتون - عملگرهای مقایسه (Comparison Operators)

در این درس با عملگرهای مقایسه آشنا می‌شویم و یاد می‌گیریم
که چگونه دو مقدار را با یکدیگر مقایسه کنیم.
"""

# ==========================================
# مقایسه اعداد
# ==========================================

# بزرگ‌تر از
print(10 > 3)      # True

# بزرگ‌تر یا مساوی
print(10 >= 3)     # True

# کوچک‌تر از
print(10 < 20)     # True

# کوچک‌تر یا مساوی
print(10 <= 20)    # True

# مساوی
print(10 == 10)    # True

# مقایسه عدد و رشته
print(10 == "10")  # False

# نامساوی
print(10 != "10")  # True


# ==========================================
# مقایسه رشته‌ها
# ==========================================

# مقایسه بر اساس ترتیب حروف در جدول Unicode
print("bag" > "apple")   # True

# حروف کوچک و بزرگ با هم متفاوت هستند
print("bag" == "BAG")    # False


# ==========================================
# بررسی کد Unicode کاراکترها
# ==========================================

# نمایش کد Unicode حرف کوچک b
print(ord("b"))

# نمایش کد Unicode حرف بزرگ B
print(ord("B"))

