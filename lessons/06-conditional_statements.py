"""
آموزش پایتون - دستورات شرطی (Conditional Statements)

در زندگی روزمره‌مون هم دائم شرط‌بندی می‌کنیم:
"اگه بارون بیاد، چتر می‌برم، وگرنه نمی‌برم."
"اگه نمرم بالای ۱۸ بشه، عالیه؛ اگه بالای ۱۰ بشه، قبولم؛ وگرنه باید دوباره بخونم."

برنامه‌ها هم دقیقاً همینطور کار می‌کنن! با دستورات شرطی به کامپیوتر می‌گیم:
"اگه این شرط درست بود، این کار رو بکن، وگرنه اون یکی رو."
"""

# ==========================================
# دستور if
# ==========================================

# if یعنی "اگر". اگر شرط جلوی if درست (True) باشه،
# فقط همون خط‌هایی که زیر if و با یک Tab فاصله (indent) نوشته شدن اجرا می‌شن.

temperature = 25

if temperature > 30:
    # این خط فقط وقتی اجرا میشه که دما بیشتر از ۳۰ باشه
    print("It's hot")
    print("Drink more water")  # این خط هم همینطور

print("Done")  # این خط همیشه اجرا میشه، چون بیرون از if نوشته شده

# خروجی این کد فقط "Done" هست، چون temperature (۲۵) بیشتر از ۳۰ نیست
# و شرط False (نادرست) میشه.


# ==========================================
# دستور else
# ==========================================

# else یعنی "وگرنه". اگه شرط if درست نبود، به جاش کدهای داخل else اجرا میشن.
# نکته: else هیچوقت شرط نداره، فقط میگه "در غیر این صورت..."

temperature = 25

if temperature > 30:
    print("It's hot")
else:
    print("It's cold")  # این خط اجرا میشه، چون ۲۵ بیشتر از ۳۰ نیست

print("Done")


# ==========================================
# دستور elif
# ==========================================

# elif یعنی "وگرنه اگر" (else + if). وقتی بیشتر از دو حالت داریم
# و می‌خوایم چند شرط رو یکی بعد از دیگری چک کنیم، از elif استفاده می‌کنیم.
# نکته مهم: پایتون شرط‌ها رو از بالا به پایین چک می‌کنه و به محض
# اینکه یکی True بشه، بقیه رو دیگه چک نمی‌کنه!

temperature = 25

if temperature > 30:
    print("It's hot")
elif temperature > 20:
    # این اجرا میشه: ۲۵ بزرگتر از ۳۰ نیست، ولی بزرگتر از ۲۰ هست
    print("It's good")
else:
    print("It's cold")

print("Done")


# ==========================================
# مثال دیگر: نمره‌ی امتحان
# ==========================================

score = 17

if score >= 18:
    print("Excellent")
elif score >= 10:
    print("Passed")   # چون ۱۷ کمتر از ۱۸ ولی بیشتر یا مساوی ۱۰ هست
else:
    print("Failed")


# ==========================================
# عملگر شرطی (Ternary Operator)
# ==========================================

# گاهی شرط خیلی ساده‌ست و فقط می‌خوایم بین دو مقدار یکی رو انتخاب کنیم.
# اون‌وقت به‌جای نوشتن ۴ خط if/else، میشه همه چیز رو در یک خط نوشت.
# این کار رو "عملگر شرطی" یا Ternary Operator می‌گن.

age = 22

# روش معمولی:
if age >= 18:
    message = "OK"
else:
    message = "Not OK"

print(message)

# همون کد بالا، ولی خلاصه‌شده در یک خط:
message = "OK" if age >= 18 else "Not OK"
print(message)


# ==========================================
# مثال کاربردی: بررسی رمز عبور
# ==========================================

password = "1234"

user_input = input("Enter password: ")

if password == user_input:
    print("Welcome!")
else:
    print("Wrong password")
    print("Try again")


# ==========================================
# عملگرهای منطقی (Logical Operators)
# ==========================================

# گاهی یک شرط کافی نیست و باید چند شرط رو با هم بسنجیم.
# برای این کار سه عملگر داریم: and (و) ، or (یا) ، not (نقیض)


# ==========================================
# عملگر and
# ==========================================

# and یعنی "و". نتیجه فقط وقتی True میشه که هر دو طرف True باشن.
# مثل وقتی که برای گرفتن وام باید هم درآمد بالا داشته باشی و هم اعتبار خوب.

high_income = False
good_credit = True

if high_income and good_credit:
    print("Accepted")
else:
    print("Not accepted")  # چون high_income برابر False هست، کل شرط False میشه


# ==========================================
# مثال
# ==========================================

is_student = True
has_valid_id = True

if is_student and has_valid_id:
    print("Student discount activated!")  # هر دو شرط True هستن
else:
    print("Discount unavailable")


# ==========================================
# عملگر or
# ==========================================

# or یعنی "یا". کافیه فقط یکی از دو طرف True باشه تا نتیجه True بشه.
# مثل ورودی سینما که یا باید بلیت داشته باشی یا دعوت‌نامه.

high_income = False
good_credit = True

if high_income or good_credit:
    print("Accepted")   # چون good_credit برابر True هست، کافیه
else:
    print("Not accepted")


# ==========================================
# مثال
# ==========================================

has_ticket = False
has_invitation = True

if has_ticket or has_invitation:
    print("You can enter")
else:
    print("Access denied")


# ==========================================
# عملگر not
# ==========================================

# not یعنی "نقیض" یا "برعکس کردن". هر مقدار True رو به False تبدیل می‌کنه
# و هر False رو به True.

high_income = False
good_credit = True
is_student = False

if (high_income or good_credit) and not is_student:
    print("Accepted")
else:
    print("Not accepted")

# بیایید مرحله به مرحله بررسی کنیم:
# high_income or good_credit  ->  False or True  ->  True
# not is_student              ->  not False       ->  True
# True and True               ->  True  =>  پس "Accepted" چاپ میشه


# ==========================================
# مثال
# ==========================================

logged_in = False

if not logged_in:
    # چون logged_in برابر False هست، not آن True میشه
    print("Please login first")


# ==========================================
# مقایسه‌های زنجیره‌ای (Chaining Comparison Operators)
# ==========================================

# گاهی می‌خوایم بررسی کنیم یک عدد بین دو مقدار دیگه قرار داره یا نه.
# پایتون به ما اجازه می‌ده این کار رو خیلی شبیه ریاضی مدرسه بنویسیم

age = 22

if 18 <= age < 65:
    print("OK")  # یعنی: آیا age هم بزرگتر یا مساوی ۱۸ هست و هم کوچکتر از ۶۵؟
else:
    print("Not allowed")

# همین شرط، به روش قدیمی‌تر و طولانی‌تر (با and):
if age >= 18 and age < 65:
    print("OK")

# هر دو کد بالا دقیقاً یک نتیجه رو می‌دن، ولی روش زنجیره‌ای خواناتر و کوتاه‌تره!

