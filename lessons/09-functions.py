# ==========================================
# انواع تابع‌ها
# ==========================================

# به صورت ساده می‌توانیم تابع‌ها را از نظر نتیجه
# به دو گروه تقسیم کنیم:
#
# 1. تابعی که یک کار را انجام می‌دهد.
# 2. تابعی که یک مقدار را برمی‌گرداند.


# ==========================================
# 1. تابعی که یک کار انجام می‌دهد
# ==========================================

def show_message(name):
    print(f"Hi {name}")


