# ==========================================
# استفاده از return در محاسبات
# ==========================================

def add(first_number, second_number):
    return first_number + second_number


result = add(10, 20)

print(result)


# ==========================================
# استفاده از نتیجه یک تابع در تابع دیگر
# ==========================================

def multiply(first_number, second_number):
    return first_number * second_number


result = multiply(add(2, 3), 4)

print(result)

# ابتدا add(2, 3) اجرا می‌شود و مقدار 5 را برمی‌گرداند.
# سپس multiply(5, 4) اجرا می‌شود.
# نتیجه نهایی 20 است.


# ==========================================
# آرگومان‌های Keyword
# ==========================================

# می‌توانیم هنگام اجرای تابع،
# نام پارامتر را نیز مشخص کنیم.

def increment(number, by):
    return number + by


result = increment(2, by=1)

print(result)

# استفاده از keyword argument می‌تواند
# خوانایی کد را بیشتر کند.

# ==========================================
# مقدار پیش‌فرض (Default Value)
# ==========================================

# می‌توانیم برای یک پارامتر مقدار پیش‌فرض تعیین کنیم.
#
# اگر کاربر مقداری برای آن پارامتر ارسال نکند،
# مقدار پیش‌فرض استفاده می‌شود.


def increase(number, by=1):
    return number + by


print(increase(2))
print(increase(2, 5))

# در مثال اول:
# by برابر 1 است.
#
# در مثال دوم:
# مقدار 5 جایگزین مقدار پیش‌فرض می‌شود.


# ==========================================
# ترتیب پارامترهای دارای مقدار پیش‌فرض
# ==========================================

# پارامترهای دارای مقدار پیش‌فرض باید بعد از
# پارامترهای اجباری قرار بگیرند.

def calculate_price(price, tax=10):
    return price + (price * tax / 100)


print(calculate_price(100))
print(calculate_price(100, 20))

# این ساختار درست است:
#
# def function(required, optional=default):
#     ...


# ==========================================
# تعداد نامشخصی از آرگومان‌ها
# ==========================================

# گاهی نمی‌دانیم کاربر چند مقدار می‌خواهد
# به تابع ارسال کند.
#
# در این شرایط می‌توانیم از *args استفاده کنیم.

def multiply(*numbers):
    result = 1

    for number in numbers:
        result *= number

    return result


print(multiply(3, 5))
print(multiply(3, 5, 6))
print(multiply(3, 5, 6, 9))


# ==========================================
# *args چگونه کار می‌کند؟
# ==========================================

# *args اجازه می‌دهد تعداد نامشخصی آرگومان
# به تابع ارسال کنیم.
#
# داخل تابع، args به صورت یک tuple در دسترس است.
#
# tuple را در درس‌های بعدی به صورت کامل بررسی می‌کنیم.

def show_numbers(*numbers):
    print(numbers)


show_numbers(10, 20, 30)

# خروجی:
# (10, 20, 30)


# ==========================================
# مثال واقعی: محاسبه میانگین
# ==========================================

def calculate_average(*numbers):
    if not numbers:
        return 0

    total = 0

    for number in numbers:
        total += number

    return total / len(numbers)


print(calculate_average(10, 20, 30))
print(calculate_average(15, 18, 20, 17))


# ==========================================
# نکته مهم درباره return
# ==========================================

# وقتی Python به return می‌رسد،
# اجرای تابع همان‌جا متوقف می‌شود.

def check_age(age):
    if age >= 18:
        return "Adult"

    return "Minor"


print(check_age(20))
print(check_age(15))


# ==========================================
# مثال واقعی: بررسی قبولی دانش‌آموز
# ==========================================

def get_result(score):
    if score >= 10:
        return "Passed"

    return "Failed"


print(get_result(18))
print(get_result(8))


