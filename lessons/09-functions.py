# اما مقداری را به برنامه برنمی‌گرداند.


# ==========================================
# 2. تابعی که یک مقدار برمی‌گرداند
# ==========================================

# برای برگرداندن یک مقدار از return استفاده می‌کنیم.

def get_greeting(name):
    return f"Hi {name}"


message = get_greeting("Shrek")

