# return باعث می‌شود نتیجه تابع را بتوانیم
# در یک متغیر ذخیره کنیم یا در جای دیگری استفاده کنیم.


# ==========================================
# تفاوت print و return
# ==========================================

def print_greeting(name):
    print(f"Hi {name}")


def get_greeting(name):
    return f"Hi {name}"


# تابع اول فقط پیام را نمایش می‌دهد.

print_greeting("Harry")


# تابع دوم مقدار را برمی‌گرداند.

message = get_greeting("Harry")
print(message)


