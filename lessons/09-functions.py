# ==========================================
# تابع چیست؟
# ==========================================

# تابع مجموعه‌ای از دستورهاست که برای انجام یک کار مشخص
# نوشته می‌شود و می‌توانیم هر زمان که لازم بود آن را اجرا کنیم.
#
# یکی از مهم‌ترین مزایای تابع‌ها این است که
# از تکرار کد جلوگیری می‌کنند.


# ==========================================
# ساخت یک تابع ساده
# ==========================================

def greet():
    print("Hi there")
    print("Welcome aboard")


# برای اجرای تابع باید نام آن را همراه با () بنویسیم.

greet()


# ==========================================
# نام‌گذاری تابع
# ==========================================

# نام تابع باید معنی مشخصی داشته باشد.
# برای نام‌گذاری تابع‌ها از snake_case استفاده می‌کنیم.
#
# نام تابع بهتر است نشان دهد که تابع چه کاری انجام می‌دهد.

def show_welcome_message():
    print("Welcome to Python")


show_welcome_message()


# ==========================================
# پارامتر (Parameter)
# ==========================================

# گاهی می‌خواهیم اطلاعاتی را به تابع ارسال کنیم.
# برای این کار هنگام تعریف تابع، پارامتر مشخص می‌کنیم.

def greet(name):
    print(f"Hi {name}")
    print("Welcome aboard")


# name یک Parameter یا پارامتر است.
#
# هنگام اجرای تابع باید یک مقدار برای آن ارسال کنیم.

greet("Jack")


# ==========================================
# مثال از چند پارامتر
# ==========================================

def greet_person(first_name, last_name):
    print(f"Hi {first_name} {last_name}")
    print("Welcome aboard")


greet_person("Jack", "Reacher")
greet_person("John", "Snow")

# first_name و last_name پارامتر هستند.
#
# "Jack" و "Reacher" آرگومان هستند.


# ==========================================
# Parameter و Argument
# ==========================================

# Parameter:
# متغیری است که هنگام تعریف تابع مشخص می‌کنیم.
#
# Argument:
# مقداری است که هنگام اجرای تابع به آن می‌دهیم.

def introduce(name, age):
    print(f"My name is {name}")
    print(f"I am {age} years old")


# name و age -> Parameter
# "Sara" و 20 -> Argument

introduce("Sara", 20)


# ==========================================
# تعداد آرگومان‌ها
# ==========================================

# تعداد آرگومان‌ها باید با تعداد پارامترهای اجباری
# تابع مطابقت داشته باشد.

def calculate_sum(first_number, second_number):
    print(first_number + second_number)


calculate_sum(10, 20)

# اگر یکی از آرگومان‌ها را حذف کنیم،
