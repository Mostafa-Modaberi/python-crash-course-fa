"""
آموزش پایتون - اعداد (Numbers)

در پایتون می‌توان با انواع مختلفی از اعداد کار کرد.
همچنین عملگرهای ریاضی و توابع مختلفی برای انجام محاسبات وجود دارد.
"""

# ==========================================
# انواع اعداد
# ==========================================

# عدد صحیح (Integer)
import math
student_count = 25

# عدد اعشاری (Float)
movie_rating = 8.7

# عدد مختلط (Complex)
complex_number = 3 + 2j

print(student_count)
print(movie_rating)
print(complex_number)


# ==========================================
# تغییر مقدار متغیر
# ==========================================

score = 10

# روش معمول
score = score + 5
print(score)

# روش کوتاه‌تر (پیشنهادی)
score += 5
print(score)

# سایر عملگرهای انتساب
score -= 3
print(score)

score *= 2
print(score)

score /= 4
print(score)


# ==========================================
# عملگرهای ریاضی
# ==========================================

print(10 + 3)     # جمع
print(10 - 3)     # تفریق
print(10 * 3)     # ضرب
print(10 / 3)     # تقسیم
print(10 // 3)    # تقسیم صحیح
print(10 % 3)     # باقیمانده تقسیم
print(10 ** 3)    # توان


# ==========================================
# گرد کردن اعداد
# ==========================================

print(round(2.4))
print(round(2.5))
print(round(2.9))

# قدر مطلق
print(abs(-12))
print(abs(-7.8))


# ==========================================
# کتابخانه math
# ==========================================

print(math.ceil(2.1))      # گرد به بالا
print(math.ceil(2.9))

print(math.floor(2.9))     # گرد به پایین
print(math.floor(2.1))


# ==========================================
# اولویت انجام عملیات
# ==========================================

print(20 / 3 + 1)

# معادل عبارت بالا
print((20 / 3) + 1)

# تغییر اولویت با پرانتز
print(20 / (3 + 1))

print((5 + 3) * 2)
print(5 + (3 * 2))


# ==========================================
# استفاده از متغیرها در محاسبات
# ==========================================

age = 16
height = 175

print(age + 2)
print(height - 10)
print(age * 2)
print(height / age)


# ==========================================
# توان
# ==========================================

print(5 ** 2)
print(5 ** 3)
print(2 ** 10)


# ==========================================
# باقیمانده تقسیم (Modulus)
# ==========================================

print(10 % 2)
print(11 % 2)
print(78 % 11)

# کاربرد:
# بررسی زوج یا فرد بودن عدد

number = 15

print(number % 2)

# اگر خروجی صفر باشد، عدد زوج است.
# اگر خروجی یک باشد، عدد فرد است.


# ==========================================
# مثال واقعی
# ==========================================

price = 19.99
count = 3

total_price = price * count

print(total_price)
print(round(total_price, 2))


