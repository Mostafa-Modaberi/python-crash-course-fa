# ==========================================
# تمرین 2 (چالش)
# ==========================================
#
# یک فروشگاه بازی‌های ویدیویی، یک بازی را با قیمت
# 49.99 دلار می‌فروشد.
#
# مشتری 4 نسخه از این بازی را خریداری می‌کند.
#
# سپس:
#
# 1- قیمت کل خرید را محاسبه و چاپ کن.
#
# 2- قیمت نهایی را با استفاده از round()
#    تا 2 رقم اعشار گرد کن و چاپ کن.
#
# 3- اگر مبلغ کل خرید بین 3 نفر تقسیم شود،
#    سهم هر نفر را محاسبه و چاپ کن.
#
# 4- تعداد بازی‌ها را به توان 3 برسان و چاپ کن.
#
# 5- با استفاده از عملگر % بررسی کن که آیا
#    تعداد بازی‌ها زوج است یا فرد.
#    (فقط مقدار باقی‌مانده را چاپ کن.)
#
# 6- با استفاده از math.ceil() و math.floor()
#    سهم هر نفر را یک بار به بالا و یک بار به پایین
